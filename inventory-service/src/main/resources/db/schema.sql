CREATE TABLE IF NOT EXISTS evento_config (
    event_id                  BIGINT      NOT NULL PRIMARY KEY,
    estado                    VARCHAR(16) NOT NULL,
    max_entradas_por_cliente  INT         NOT NULL DEFAULT 6,
    actualizado_en            TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE IF NOT EXISTS reserva (
    id                 UUID PRIMARY KEY,
    event_id           BIGINT        NOT NULL,
    sector_id          BIGINT        NOT NULL,
    tipo_sector        VARCHAR(16)   NOT NULL,
    cliente_id         BIGINT        NOT NULL,
    cantidad           INT           NOT NULL,
    precio_unitario    NUMERIC(12,2) NOT NULL,
    importe_total      NUMERIC(12,2) NOT NULL,
    estado             VARCHAR(16)   NOT NULL,
    clave_idempotencia VARCHAR(100),
    creada_en          TIMESTAMP WITH TIME ZONE NOT NULL,
    expira_en          TIMESTAMP WITH TIME ZONE NOT NULL,
    confirmada_en      TIMESTAMP WITH TIME ZONE,
    liberada_en        TIMESTAMP WITH TIME ZONE,
    motivo_liberacion  VARCHAR(120),
    CONSTRAINT uk_reserva_idempotencia UNIQUE (clave_idempotencia),
    CONSTRAINT ck_reserva_estado CHECK (estado IN ('ACTIVA', 'CONFIRMADA', 'LIBERADA', 'VENCIDA')),
    CONSTRAINT ck_reserva_cantidad CHECK (cantidad > 0)
);

CREATE INDEX IF NOT EXISTS ix_reserva_cliente ON reserva (event_id, cliente_id);
CREATE INDEX IF NOT EXISTS ix_reserva_expira ON reserva (estado, expira_en);

CREATE TABLE IF NOT EXISTS evento_asiento (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id        BIGINT      NOT NULL,
    sector_id       BIGINT      NOT NULL,
    asiento_id      BIGINT      NOT NULL,
    fila            VARCHAR(20),
    numero          VARCHAR(20),
    estado          VARCHAR(16) NOT NULL,
    reserva_id      UUID,
    vence_en        TIMESTAMP WITH TIME ZONE,
    actualizado_en  TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_evento_asiento UNIQUE (event_id, sector_id, asiento_id),
    CONSTRAINT ck_evento_asiento_estado CHECK (estado IN ('LIBRE', 'RETENIDO', 'VENDIDO')),
    CONSTRAINT fk_evento_asiento_reserva FOREIGN KEY (reserva_id) REFERENCES reserva (id)
);

CREATE INDEX IF NOT EXISTS ix_evento_asiento_sector ON evento_asiento (event_id, sector_id);
CREATE INDEX IF NOT EXISTS ix_evento_asiento_vence ON evento_asiento (estado, vence_en);
CREATE INDEX IF NOT EXISTS ix_evento_asiento_reserva ON evento_asiento (reserva_id);

CREATE TABLE IF NOT EXISTS zona_cupo (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id       BIGINT    NOT NULL,
    sector_id      BIGINT    NOT NULL,
    capacidad      INT       NOT NULL,
    vendidos       INT       NOT NULL DEFAULT 0,
    retenidos      INT       NOT NULL DEFAULT 0,
    actualizado_en TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_zona_cupo UNIQUE (event_id, sector_id),
    CONSTRAINT ck_zona_cupo_capacidad CHECK (capacidad > 0),
    CONSTRAINT ck_zona_cupo_sin_sobreventa CHECK (vendidos >= 0 AND retenidos >= 0 AND vendidos + retenidos <= capacidad)
);
